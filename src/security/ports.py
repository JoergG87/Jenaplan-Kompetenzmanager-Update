"""Application-facing ports for the local security core."""

from __future__ import annotations

from datetime import datetime
from pathlib import Path
from typing import Protocol, Sequence

from .domain import AccountRecord, RecoveryCodeCandidate, RecoveryCodeHash


class RandomSource(Protocol):
    def bytes(self, length: int) -> bytes: ...
    def uuid4(self) -> str: ...


class UtcClock(Protocol):
    def utc_now(self) -> datetime: ...


class MonotonicClock(Protocol):
    def monotonic(self) -> float: ...


class PasswordHasher(Protocol):
    def hash(self, password: str, salt: bytes) -> str: ...
    def verify(self, password_hash: str, password: str) -> bool: ...
    def needs_rehash(self, password_hash: str) -> bool: ...


class EnrollmentMarkerStore(Protocol):
    @property
    def path(self) -> Path: ...
    def exists(self) -> bool: ...
    def read_reference(self) -> str: ...
    def publish(self, marker_reference: str) -> None: ...


class FilePermissionManager(Protocol):
    def prepare_directory(self, path: Path) -> None: ...
    def secure_file(self, path: Path) -> None: ...
    def secure_sqlite_files(self, database_path: Path) -> None: ...
    def verify(self, security_directory: Path) -> bool | None: ...


class SecurityRepository(Protocol):
    @property
    def database_path(self) -> Path: ...
    def exists(self) -> bool: ...
    def inspect(self) -> tuple[int, int, str, AccountRecord]: ...
    def initialize(
        self,
        *,
        installation_id: str,
        marker_reference: str,
        user_id: str,
        password_hash: str,
        hash_format_version: int,
        recovery_set_id: str,
        recovery_codes: Sequence[RecoveryCodeHash],
        now: datetime,
    ) -> None: ...
    def load_account(self) -> AccountRecord: ...
    def record_login_failure(self, *, now: datetime) -> AccountRecord: ...
    def record_login_success(
        self, *, now: datetime, replacement_hash: str | None = None
    ) -> AccountRecord: ...
    def update_observed_login_time(
        self, *, observed: datetime, locked_until: datetime | None = None
    ) -> AccountRecord: ...
    def change_password(
        self, *, expected_hash: str, replacement_hash: str, now: datetime
    ) -> bool: ...
    def active_recovery_codes(self) -> tuple[RecoveryCodeCandidate, ...]: ...
    def record_recovery_failure(self, *, now: datetime) -> AccountRecord: ...
    def update_observed_recovery_time(
        self, *, observed: datetime, locked_until: datetime | None = None
    ) -> AccountRecord: ...
    def consume_recovery_code(
        self, *, recovery_code_id: str, expected_digest: bytes, now: datetime
    ) -> bool: ...
    def prepare_recovery_set(
        self,
        *,
        recovery_set_id: str,
        recovery_codes: Sequence[RecoveryCodeHash],
        now: datetime,
    ) -> None: ...
    def confirm_recovery_set(self, *, recovery_set_id: str, now: datetime) -> bool: ...
    def complete_password_reset(
        self,
        *,
        replacement_hash: str,
        recovery_set_id: str,
        recovery_codes: Sequence[RecoveryCodeHash],
        now: datetime,
    ) -> bool: ...
