"""Application-facing ports for the local security core."""

from __future__ import annotations

from datetime import datetime
from pathlib import Path
from typing import Protocol, Sequence

from .domain import (
    AccountRecord,
    DeviceCredential,
    RecoveryCodeCandidate,
    RecoveryCodeHash,
    SecurityBackupProof,
    SupportPublicKey,
    SupportResetPayload,
    SupportResetRequest,
    LocalAuthenticationAvailability,
    LocalAuthenticationResult,
    SecretStoreReadResult,
)

if False:  # pragma: no cover - typing-only imports without a runtime cycle
    from .data_keys import DataKeyset, DataMasterKeyReadResult


class RandomSource(Protocol):
    def bytes(self, length: int) -> bytes: ...
    def uuid4(self) -> str: ...


class UtcClock(Protocol):
    def utc_now(self) -> datetime: ...


class MonotonicClock(Protocol):
    def monotonic(self) -> float: ...


class PasswordHasher(Protocol):
    def hash(self, password: str, salt: bytes) -> str: ...
    def verify(self, password_hash: str, password: str) -> bool: ...
    def needs_rehash(self, password_hash: str) -> bool: ...


class EnrollmentMarkerStore(Protocol):
    @property
    def path(self) -> Path: ...
    def exists(self) -> bool: ...
    def read_reference(self) -> str: ...
    def publish(self, marker_reference: str) -> None: ...


class FilePermissionManager(Protocol):
    def prepare_directory(self, path: Path) -> None: ...
    def secure_file(self, path: Path) -> None: ...
    def secure_sqlite_files(self, database_path: Path) -> None: ...
    def verify(self, security_directory: Path) -> bool | None: ...


class SupportResetSignatureVerifier(Protocol):
    def verify(self, public_key: bytes, message: bytes, signature: bytes) -> bool: ...


class SupportPublicKeyRegistry(Protocol):
    def get(self, key_id: str) -> SupportPublicKey | None: ...
    def key_ids(self) -> tuple[str, ...]: ...


class SupportSecurityBackupPort(Protocol):
    def create_and_verify(self) -> SecurityBackupProof: ...


class DeviceCredentialRepository(Protocol):
    def active_device_credential(self) -> DeviceCredential | None: ...
    def pending_device_credentials(self) -> tuple[DeviceCredential, ...]: ...
    def revoked_device_credentials(self) -> tuple[DeviceCredential, ...]: ...
    def prepare_device_credential(self, credential: DeviceCredential) -> None: ...
    def activate_device_credential(
        self, *, credential_id: str, now: datetime
    ) -> str | None: ...
    def touch_device_credential(
        self, *, credential_id: str, now: datetime
    ) -> bool: ...
    def revoke_device_credential(
        self, *, credential_id: str, now: datetime
    ) -> bool: ...
    def revoke_all_device_credentials(self, *, now: datetime) -> tuple[str, ...]: ...


class DeviceSecretStore(Protocol):
    @property
    def supported(self) -> bool: ...
    def create(self, *, installation_id: str, credential_id: str, secret: bytes) -> None: ...
    def read(self, *, installation_id: str, credential_id: str) -> SecretStoreReadResult: ...
    def delete(self, *, installation_id: str, credential_id: str) -> bool: ...


class DataKeysetRepository(Protocol):
    def active_data_keyset(self) -> "DataKeyset | None": ...
    def pending_data_keysets(self) -> tuple["DataKeyset", ...]: ...
    def data_keysets_for_cleanup(self) -> tuple["DataKeyset", ...]: ...
    def next_data_key_generation(self) -> int: ...
    def prepare_data_keyset(self, keyset: "DataKeyset") -> None: ...
    def activate_data_keyset(self, *, key_id: str) -> "DataKeyset": ...
    def fail_data_keyset(self, *, key_id: str) -> bool: ...
    def revoke_data_keyset(self, *, key_id: str) -> bool: ...


class DataMasterKeyStore(Protocol):
    """Platform port for macOS Keychain and a future Windows DPAPI adapter."""

    @property
    def supported(self) -> bool: ...
    def create(
        self, *, installation_id: str, key_id: str, key_material: bytes
    ) -> None: ...
    def read(
        self, *, installation_id: str, key_id: str
    ) -> "DataMasterKeyReadResult": ...
    def delete(self, *, installation_id: str, key_id: str) -> bool: ...


class LocalDeviceAuthenticator(Protocol):
    def availability(self) -> LocalAuthenticationAvailability: ...
    def authenticate(self, reason: str) -> LocalAuthenticationResult: ...


class SecurityRepository(Protocol):
    @property
    def database_path(self) -> Path: ...
    def exists(self) -> bool: ...
    def inspect(self) -> tuple[int, int, str, AccountRecord]: ...
    def initialize(
        self,
        *,
        installation_id: str,
        marker_reference: str,
        user_id: str,
        password_hash: str,
        hash_format_version: int,
        recovery_set_id: str,
        recovery_codes: Sequence[RecoveryCodeHash],
        now: datetime,
        pending: bool = False,
    ) -> None: ...
    def activate_pending_account(
        self, *, recovery_set_id: str, now: datetime
    ) -> bool: ...
    def load_account(self) -> AccountRecord: ...
    def record_login_failure(self, *, now: datetime) -> AccountRecord: ...
    def record_login_success(
        self, *, now: datetime, replacement_hash: str | None = None
    ) -> AccountRecord: ...
    def update_observed_login_time(
        self, *, observed: datetime, locked_until: datetime | None = None
    ) -> AccountRecord: ...
    def change_password(
        self, *, expected_hash: str, replacement_hash: str, now: datetime
    ) -> bool: ...
    def active_recovery_codes(self) -> tuple[RecoveryCodeCandidate, ...]: ...
    def record_recovery_failure(self, *, now: datetime) -> AccountRecord: ...
    def update_observed_recovery_time(
        self, *, observed: datetime, locked_until: datetime | None = None
    ) -> AccountRecord: ...
    def consume_recovery_code(
        self, *, recovery_code_id: str, expected_digest: bytes, now: datetime
    ) -> bool: ...
    def prepare_recovery_set(
        self,
        *,
        recovery_set_id: str,
        recovery_codes: Sequence[RecoveryCodeHash],
        now: datetime,
    ) -> None: ...
    def confirm_recovery_set(self, *, recovery_set_id: str, now: datetime) -> bool: ...
    def complete_password_reset(
        self,
        *,
        replacement_hash: str,
        recovery_set_id: str,
        recovery_codes: Sequence[RecoveryCodeHash],
        now: datetime,
    ) -> bool: ...
    def prepare_password_reset(
        self,
        *,
        replacement_hash: str,
        recovery_set_id: str,
        recovery_codes: Sequence[RecoveryCodeHash],
        now: datetime,
    ) -> bool: ...
    def confirm_password_reset(
        self, *, recovery_set_id: str, now: datetime
    ) -> bool: ...
    def create_support_reset_request(self, request: SupportResetRequest) -> None: ...
    def load_support_reset_request(
        self, reset_request_id: str
    ) -> SupportResetRequest | None: ...
    def support_token_digest_used(self, token_digest: bytes) -> bool: ...
    def consume_support_reset(
        self,
        *,
        payload: SupportResetPayload,
        token_digest: bytes,
        now: datetime,
    ) -> int | None: ...
    def security_epoch(self) -> int: ...
